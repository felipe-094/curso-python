# Las condicionales if-else nos permiten ejecutar un bloque de código u otro dependiendo de si una condición es verdadera o falsa.

contraseña_almacenada = "felipeMaestro"
contraseña_escrita = '''felipeMaestro'''

if contraseña_almacenada == contraseña_escrita:
    print("INICIANDO SESION...")
else:
    print("CONTRASEÑA EQUIVOCADA, INTENTE DE NUEVO")
    