#Las tuplas son un tipo de dato en python que se utilizan para almacenar una secuencia de elementos. A diferencia de las listas, las tuplas son inmutables, lo que significa que no se pueden modificar una vez que se han creado. Las tuplas se definen utilizando paréntesis () y los elementos se separan por comas.

#creando tuplas con tuple()
tupla = tuple(["pipe1", "pipe2"])

#creando una tupla sin parentesis de multiples datos
tupla = "pipe1","pipe2"

#creando una tupla sin parentesis de un solo dato
tupla = "pipe"

print(type(tupla))