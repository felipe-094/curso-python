            #    OPERADORES DE PERTENECIA (IN / NOT IN)
            
# definidendo una variable con camelCase
nombreCompletoDeTuTioMaster = "Luis felipe"

# Definiendo una variable con snake_case 
nombre_completo_de_tu_tio_master = "Luis felipe" 

#concatenar con +
bienvenida = "Hola " + " ¿Como estas?"

#concatenar con f-strings
bienvenida = f"Hola {nombre_completo_de_tu_tio_master} ¿Como estas?"

# operadores de pertenencia (in / not in)
print("felipe" in bienvenida)  # True
print("felipe" not in bienvenida)  # false